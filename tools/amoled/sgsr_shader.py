"""Adapt pinned BSD SGSR1 to decoder external-OES textures without an extra copy pass."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
VENDOR = ROOT / "tools/amoled/vendor/sgsr1/sgsr1_shader_mobile.frag"
DESTINATION = ROOT / "cobalt/android/apk/app/src/main/java/dev/cobalt/updates/SgsrShader.java"
PINNED_SHA256 = "93e8db987dc79f62e68805f968d63989e5d50daebe4d040e4c7104047ad49139"


def generated_source():
    raw = VENDOR.read_bytes()
    if hashlib.sha256(raw).hexdigest() != PINNED_SHA256:
        raise ValueError("The pinned Qualcomm SGSR1 shader changed; review before building")
    shader = raw.decode().replace("#version 300 es", "#extension GL_OES_EGL_image_external : require")
    shader = shader.replace("precision mediump float;", "precision highp float;")
    shader = shader.replace("uniform mediump sampler2D ps0;", "uniform samplerExternalOES ps0;")
    shader = shader.replace("layout(location=0) in highp vec4 in_TEXCOORD0;", "varying highp vec4 in_TEXCOORD0;")
    shader = shader.replace("layout(location=0) out vec4 out_Target0;", "")
    helpers = """
uniform mat4 textureTransform;
uniform float upscalerEnabled;
vec4 sampleFrame(vec2 uv) {
    uv = clamp(uv, 0.5 * ViewportInfo[0].xy, vec2(1.0) - 0.5 * ViewportInfo[0].xy);
    return texture2D(ps0, (textureTransform * vec4(uv, 0.0, 1.0)).xy);
}
// Exact GLSL textureGather component ordering. OES has no textureGather;
// sample the four texel centers instead, preserving the SurfaceTexture crop/flip.
vec4 gatherGreen(vec2 uv) {
    vec2 texel = ViewportInfo[0].xy;
    vec2 base = (floor(uv * ViewportInfo[0].zw - 0.5) + 0.5) * texel;
    return vec4(sampleFrame(base + vec2(0.0, texel.y)).g,
                sampleFrame(base + texel).g,
                sampleFrame(base + vec2(texel.x, 0.0)).g, sampleFrame(base).g);
}
"""
    shader = shader.replace("float fastLanczos2", helpers + "\nfloat fastLanczos2")
    shader = shader.replace("textureLod(ps0,in_TEXCOORD0.xy,0.0)", "sampleFrame(in_TEXCOORD0.xy)")
    shader = shader.replace("textureGather(ps0,", "gatherGreen(").replace(", mode)", ")").replace(",mode)", ")")
    shader = shader.replace("int mode = OperationMode;", """if (upscalerEnabled < 0.5) {
        gl_FragColor = vec4(sampleFrame(in_TEXCOORD0.xy).rgb, 1.0); return;
    }
    int mode = OperationMode;""")
    # Guard flat/near-flat blocks against half/float underflow and zero division.
    shader = shader.replace("2.181818/sum", "2.181818/max(sum, 0.00001)")
    shader = shader.replace("aWY.y/aWY.x", "(abs(aWY.x) < 0.00001 ? color.w : aWY.y/aWY.x)")
    shader = shader.replace("out_Target0.xyzw = color;", "gl_FragColor = color;")
    shader = shader.replace("highp vec2(", "vec2(")
    vertex = """attribute vec2 position;
varying highp vec4 in_TEXCOORD0;
void main() {
    gl_Position = vec4(position, 0.0, 1.0);
    in_TEXCOORD0 = vec4(position * 0.5 + 0.5, 0.0, 1.0);
}
"""
    def literal(value):
        return " +\n      ".join(json.dumps(line + "\n") for line in value.splitlines())
    return """// Generated by tools/amoled/sgsr_shader.py; do not hand edit.
// SGSR1 Copyright (c) 2025 Qualcomm Innovation Center, Inc. BSD-3-Clause.
// See tools/amoled/vendor/sgsr1/LICENSE; a copy is included in each APK.
package dev.cobalt.updates;
public final class SgsrShader {
  private SgsrShader() {}
  public static final String VERTEX = %s;
  public static final String FRAGMENT = %s;
}
""" % (literal(vertex), literal(shader))


if __name__ == "__main__":
    DESTINATION.write_text(generated_source())
